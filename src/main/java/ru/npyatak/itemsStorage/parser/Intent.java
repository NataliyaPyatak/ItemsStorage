package ru.npyatak.itemsStorage.parser;

/**
 * Намерение пользователя, распознанное из фразы.
 *
 * @author natalapatak
 * @since 27.09.2026
 */
public enum Intent
{
    /** Положить/переложить/убрать — обновляет место вещи, если она уже записана */
    PUT,
    /** Добавить — создаёт новую запись */
    ADD,
    /** Где вещь / найди вещь */
    FIND,
    /** Что лежит в месте */
    WHAT_IN,
    /** Удалить вещь */
    DELETE,
    /** Не распознано */
    UNKNOWN
}
